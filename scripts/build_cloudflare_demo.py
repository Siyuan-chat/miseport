"""Freeze only validated synthetic data and export Python parity vectors."""
import asyncio
import json
from pathlib import Path
from miseport import __version__
from miseport.importers import load_catalog
from miseport.server import create_server

root = Path(__file__).resolve().parents[1]
destination = root / "cloudflare"
destination.mkdir(exist_ok=True)
catalog = load_catalog(root / "references/legacy-20261027/demo-store.reference.json")
if not catalog.products or not all(p.is_demo is True for p in catalog.products):
    raise SystemExit("Refuse to bundle non-demo data")
products = [p.model_dump(mode="json") for p in catalog.products]
def safe_numbers(value):
    if isinstance(value, int) and not isinstance(value, bool) and abs(value) > 9007199254740991:
        raise ValueError("Value exceeds JavaScript safe integer range")
    if isinstance(value, dict):
        for child in value.values(): safe_numbers(child)
    if isinstance(value, list):
        for child in value: safe_numbers(child)
safe_numbers(products)
tools = asyncio.run(create_server(catalog, transport="streamable-http").list_tools())
data = {"version": __version__, "products": products, "metadata": catalog.metadata,
        "tools": [tool.model_dump(mode="json", by_alias=True, exclude_none=True) for tool in tools]}
(destination / "generated-catalog.mjs").write_text(
    "// Generated by scripts/build_cloudflare_demo.py. Synthetic data only.\nexport default "
    + json.dumps(data, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
cases = []
def case(method, *args):
    cases.append({"method": method, "args": list(args), "expected": getattr(catalog, method)(*args)})
for sku in ("tea-001", "tea-002", "missing"):
    for method in ("detail", "inventory", "jsonld"):
        case(method, sku)
    for quantity in (1, 2, 13, 1000):
        case("quote", sku, quantity)
case("audit")
for query in ("", "ほうじ茶", "京都", "抹茶", "見つからない", "ｷﾞﾌﾄ"):
    case("search", query)
case("search", "", None, None, 2000)
case("search", "", None, None, None, True)
case("search", "", None, None, None, False, 1, 1)
case("search", "", None, None, None, False, 20, 0, True, "京都府")
case("search", "", None, None, None, False, 20, 0, False)
(destination / "contract-cases.json").write_text(
    json.dumps({"source": "Python reference catalog operations, not Muse evaluation", "cases": cases},
               ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
print(f"Frozen {len(products)} synthetic products, {len(tools)} tools, {len(cases)} Python parity cases.")
